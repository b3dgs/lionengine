package com.b3dgs.lionengine.audio.codec.ogg;

import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;

import com.b3dgs.lionengine.audio.PcmBuffer;
import com.b3dgs.lionengine.audio.WavDecoder;

/**
 * The OGG Vorbis test files and their libvorbisfile decodings, generated by {@code src/test/generate-ogg.sh} (ADR-0073).
 */
final class OggFiles
{
    /** Mono, 22,050 Hz, 0.5 s. */
    static final String MONO_22050 = "mono-22050";
    /** Mono, 11,025 Hz, 0.5 s. */
    static final String MONO_11025 = "mono-11025";
    /** Mono, 22,050 Hz, 5 s, on five audio pages. */
    static final String LONG_MONO_22050 = "long-mono-22050";
    /** Mono, 48,000 Hz, 0.25 s. */
    static final String MONO_48000 = "mono-48000";
    /** Stereo, 44,100 Hz, 0.25 s. */
    static final String STEREO_44100 = "stereo-44100";
    /** Three channels, 22,050 Hz, 0.1 s: refused. */
    static final String THREE_CHANNELS = "three-channels";
    /** Largest difference to the libvorbisfile decoding, in 16-bit steps: the float rounding of another implementation. */
    static final int TOLERANCE = 1;

    /**
     * Reads a test file.
     *
     * @param name The file name.
     * @return The bytes.
     */
    static byte[] bytes(String name)
    {
        try (InputStream input = OggFiles.class.getResourceAsStream(name))
        {
            if (input == null)
            {
                throw new IllegalArgumentException("Missing test file: " + name);
            }
            return input.readAllBytes();
        }
        catch (final IOException exception)
        {
            throw new UncheckedIOException(exception);
        }
    }

    /**
     * Reads an OGG test file.
     *
     * @param sound The sound name.
     * @return The bytes of its OGG file.
     */
    static byte[] ogg(String sound)
    {
        return bytes(sound + ".ogg");
    }

    /**
     * Reads the libvorbisfile decoding of an OGG test file.
     *
     * @param sound The sound name.
     * @return The samples decoded by libvorbisfile.
     */
    static PcmBuffer reference(String sound)
    {
        try
        {
            return new WavDecoder().decode(new ByteArrayInputStream(bytes(sound + ".reference.wav")));
        }
        catch (final IOException exception)
        {
            throw new UncheckedIOException(exception);
        }
    }

    /**
     * Returns all the samples of a buffer.
     *
     * @param buffer The buffer.
     * @return The interleaved samples.
     */
    static short[] samples(PcmBuffer buffer)
    {
        final short[] samples = new short[buffer.getFrames() * buffer.getFormat().channels()];
        buffer.readFrames(0, samples, 0, buffer.getFrames());
        return samples;
    }

    /**
     * Returns the largest difference between two sample arrays of the same length.
     *
     * @param expected The expected samples.
     * @param actual The actual samples.
     * @return The largest absolute difference.
     */
    static int maxDifference(short[] expected, short[] actual)
    {
        if (expected.length != actual.length)
        {
            throw new IllegalArgumentException("Lengths differ: " + expected.length + " and " + actual.length);
        }
        int max = 0;
        for (int i = 0; i < expected.length; i++)
        {
            max = Math.max(max, Math.abs(expected[i] - actual[i]));
        }
        return max;
    }

    /**
     * Private constructor.
     */
    private OggFiles()
    {
        throw new AssertionError();
    }
}
